"""Which (environment, tier) tasks stay hard enough to ship: the 75% selection rule.

usage: python experiments/selection.py [--threshold 0.75]

A task is kept when the best agent model's pass rate on it is below the threshold. The pass
rate is QEC-Drift's rule applied per instance (shared_table.py: the "changed" answer is right,
on a changed instance at least half the diagnosis credit, and at least half the gap closed
where a fix is graded), averaged over that model's rollouts, on the paper seeds. The best model
is the one with the highest pass rate. A task with no agent runs yet is "pending": it can only
be provisionally kept, on the evidence that the reference (the strongest known method) is
below the threshold. Native scores (trivial 0.50) are reported next to the pass rates.

Writes experiments/results/selection.json and selection.md. Licence: Apache-2.0.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict

import numpy as np

import analyze
from shared_table import mismatch_rows

THRESHOLD = 0.75
TIERS = ("standard", "hard")


def task_stats(tier: str) -> dict:
    """Per env: pass rate and native score of the reference, the trivial floor and each agent
    model (rollouts averaged), on the paper seeds."""
    analyze.TIER = tier
    rows = [r for r in mismatch_rows(analyze.load()) if r["seed_set"] == "paper"]
    groups = defaultdict(list)  # (env, label, rollout) -> rows
    for r in rows:
        if r["kind"] == "agent":
            groups[(r["task"], r["model"], r["rollout"])].append(r)
        elif r["solution"] in ("reference", "trivial"):
            groups[(r["task"], r["solution"], "")].append(r)
    out: dict = defaultdict(dict)
    for (env, label, rollout), rs in groups.items():
        d = out[env].setdefault(label, dict(pass_rates=[], scores=[], n=0))
        d["pass_rates"].append(float(np.mean([r["passed"] for r in rs])))
        d["scores"].append(float(np.mean([r["score"] for r in rs])))
        d["n"] += len(rs)
    for env in out:
        for d in out[env].values():
            d["pass_rate"] = float(np.mean(d.pop("pass_rates")))
            d["score"] = float(np.mean(d.pop("scores")))
    return dict(out)


def decide(stats: dict, threshold: float) -> dict:
    agents = {k: v for k, v in stats.items() if k not in ("reference", "trivial")}
    ref = stats.get("reference", {})
    if not agents:
        keep = ref.get("pass_rate", 1.0) < threshold
        return dict(status="pending" if keep else "excluded", best=None, best_pass=None,
                    reason=f"no agent runs; reference pass {ref.get('pass_rate', float('nan')):.2f}")
    best = max(agents, key=lambda k: agents[k]["pass_rate"])
    p = agents[best]["pass_rate"]
    return dict(status="included" if p < threshold else "excluded", best=best, best_pass=p,
                reason=f"best agent {best} passes {p:.2f}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--threshold", type=float, default=THRESHOLD)
    a = ap.parse_args()
    table = []
    for tier in TIERS:
        for env, stats in task_stats(tier).items():
            table.append(dict(env=env, tier=tier, **decide(stats, a.threshold), stats=stats))
    (analyze.OUT / "selection.json").write_text(json.dumps(
        dict(threshold=a.threshold, rule=__doc__.split("\n\n")[1], tasks=table), indent=1))
    lines = [f"# Task selection: keep a task if the best agent passes under {a.threshold:.0%}",
             "", "Generated by experiments/selection.py; do not edit. Paper seeds only. "
             "Each cell: pass rate (QEC-Drift rule) / native score (trivial 0.50).", "",
             "| task | tier | status | reference | " + " | ".join(
                 m for m in ("claude-opus-5-5", "claude-sonnet-5-5", "claude-haiku-5-5"))
             + " | reason |", "|---|---|---|---|---|---|---|---|"]
    for t in table:
        s = t["stats"]
        cell = (lambda k: f"{s[k]['pass_rate']:.2f} / {s[k]['score']:.2f}" if k in s else "not run")
        lines.append(f"| {t['env']} | {t['tier']} | {t['status']} | {cell('reference')} | "
                     + " | ".join(cell(m) for m in ("claude-opus-5-5", "claude-sonnet-5-5",
                                                     "claude-haiku-5-5"))
                     + f" | {t['reason']} |")
    (analyze.OUT / "selection.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
