"""Hidden device and grader for qec_drift_d3. Not shown to the solver.

The device is a distance-3 rotated surface code memory experiment (Z basis, 3 rounds, 17 qubits)
generated by Stim. The nominal model has uniform circuit noise. Every qubit also has a hidden
background error factor (log-normal) that the nominal model leaves out; it is the same before and
after any change. About half of the instances are controls. The rest carry one change: a hot qubit
(present for the whole new batch, or switching on inside it), a worse two-qubit gate pair, or one
correlated burst that decays inside the batch, or a qubit coupled to a switching two-level
system (random telegraph: its error rate jumps between background and hot).

Scoring is exact (eval/exact.py): every logical error rate is computed from the full joint
distribution of syndromes and logical flips of the device as it is after the batch, with no
sampling noise. The solver returns a detector error model; the grader decodes it with PyMatching.
Licence: Apache-2.0.
"""

from __future__ import annotations

import math
import sys
from dataclasses import asdict, dataclass, field

import numpy as np
import pymatching
import stim

import rubric
from _isolate import run_solver
from exact import Table, cache_load, cache_save

DISTANCE, ROUNDS = 3, 3
P_NOMINAL = 2e-3  # assumption, same order as reported superconducting gate errors
SHOT_PERIOD_US = 100.0  # McEwen 2022, arXiv 2104.05219, Fig. 1c
N_PRE = N_POST = 50_000
BACKGROUND_SIGMA = 0.3  # log-normal spread of per-qubit error factors (assumption)
HOT_RANGE = (2.0, 10.0)  # log-uniform; Burnett 2019 (>2x in T1), Klimov 2018 (up to 10x in T1)
COUPLER_RANGE = (2.0, 10.0)  # log-uniform (assumption)
BURST_DECAY_MS = (15.0, 40.0)  # log-uniform around the 25 ms of McEwen 2022 (spread: assumption)
BURST_AMPLITUDE = (2.0, 10.0)  # peak error multiplier at the burst centre (assumption)
BURST_RADIUS = (2.0, 6.0)  # Gaussian spatial radius in lattice units (assumption)
# Telegraph TLS: symmetric switching, mean dwell 0.3 to 1.5 s (log-uniform) around the 2.2 s
# switching time of Berritta et al. 2026 (arXiv 2608.02086); on-state factor 3 to 10 (Klimov
# 2018 range, floor raised so the switching is visible; assumption). Draws are kept only if the
# post batch shows at least 3 switches and 20 to 80 percent on-time, so the label is supported.
TLS_DWELL_S = (0.3, 1.5)
TLS_RANGE = (3.0, 10.0)
TLS_MIN_SWITCHES, TLS_ON_FRAC = 3, (0.2, 0.8)
DWELL_TOL = 2.0
GAP_GATE = 0.05  # change opens a decoding gap: graded on fix, else on diagnosis only
HARM_FREE, HARM_ZERO = 0.01, 0.10  # "do no harm": full credit within +1%, none at +10%
FACTOR_TOL = 1.25
ONSET_TOL_HOT = 1000  # shots
ONSET_TOL_BURST = 25  # shots
SOLVE_TIMEOUT_S = 600
MAX_DEM_BYTES = 5_000_000

# Hard tier: the listed families drawn weak (ranges are assumptions on the low side of the cited
# ones: Burnett 2019, T1 fluctuates by more than 2x; McEwen 2024, gap-engineered chips see weaker
# bursts), plus a change TASK.md does not list ("other"): a correlated two-qubit depolarizing
# error on two nearby data qubits that share no gate, once per round after the data qubits' own
# depolarization (unmodeled crosstalk; Sarovar et al. 2020, arXiv 1908.09855). Its probability is
# log-uniform in CORR_P (assumption, one to five times the nominal error). Every changed draw is
# kept only if the new batch carries at least EVIDENCE_MIN nats of expected log-likelihood ratio,
# changed against before-change device, computed exactly (eval/evidence.py).
CORR_P = (2e-3, 1e-2)
CORR_MAX_DIST = 2.9  # lattice units: data qubits two sites apart, straight or diagonal
UNLISTED = "other"
TIERS = {
    "standard": {"hot": HOT_RANGE, "coupler": COUPLER_RANGE, "tls": TLS_RANGE,
                 "burst": BURST_AMPLITUDE, "seed": 20261114},
    "hard": {"hot": (1.2, 2.5), "coupler": (1.2, 2.5), "tls": (1.3, 3.0),
             "burst": (1.3, 4.0), "corr": CORR_P, "seed": 20261118, "salt": [2]},
}
EVIDENCE_MIN = 20.0  # nats; derivation in TASK.md (hard tier) and NOTES.md
PUBLIC_SEED = TIERS["standard"]["seed"]
FAMILY_MIX =(["none"] * 10 + ["hot"] * 2 + ["onset"] * 2 + ["coupler"] * 2 + ["burst"] * 2
              + ["tls"] * 2)
QUICK_MIX = ["none", "none", "hot", "tls"]
HARD_MIX = (["none"] * 10 + ["corr"] * 5 + ["hot", "onset", "coupler", "burst", "tls"])
HARD_QUICK_MIX = ["none", "none", "corr", "tls"]
NOISE_ARITY = {"DEPOLARIZE1": 1, "DEPOLARIZE2": 2, "X_ERROR": 1, "Z_ERROR": 1}


def nominal_circuit(p: float = P_NOMINAL) -> stim.Circuit:
    return stim.Circuit.generated(
        "surface_code:rotated_memory_z", distance=DISTANCE, rounds=ROUNDS,
        after_clifford_depolarization=p, before_round_data_depolarization=p,
        before_measure_flip_probability=p, after_reset_flip_probability=p,
    ).flattened()


def scaled_circuit(base: stim.Circuit, qf: dict, pf: dict | None = None) -> stim.Circuit:
    """Multiply each noise channel by the largest qf[q] of the qubits it touches, and a
    two-qubit channel also by pf[pair]. This "every channel touching the qubit" fault model is an
    assumption (a T1 defect would mostly raise idle and measurement error)."""
    pf = pf or {}
    out = stim.Circuit()
    for ins in base:
        if ins.name not in NOISE_ARITY:
            out.append(ins)
            continue
        k, p, targets = NOISE_ARITY[ins.name], ins.gate_args_copy()[0], ins.targets_copy()
        groups: dict[float, list] = {}
        for i in range(0, len(targets), k):
            g = targets[i : i + k]
            f = max(qf.get(t.value, 1.0) for t in g)
            if k == 2:
                f *= pf.get(frozenset(t.value for t in g), 1.0)
            groups.setdefault(f, []).extend(g)
        for f, g in groups.items():
            out.append(ins.name, g, [min(p * f, 0.5)])
    return out


def gate_pairs(base: stim.Circuit) -> list[tuple[int, int]]:
    pairs = set()
    for ins in base:
        if ins.name == "DEPOLARIZE2":
            t = ins.targets_copy()
            pairs.update(tuple(sorted((t[i].value, t[i + 1].value))) for i in range(0, len(t), 2))
    return sorted(pairs)


def data_qubit_list(base: stim.Circuit) -> list[int]:
    coords = base.get_final_qubit_coordinates()
    return [q for q in sorted(coords) if coords[q][0] % 2 == 1]


def corr_pairs(base: stim.Circuit) -> list[tuple[int, int]]:
    """Data-qubit pairs within CORR_MAX_DIST (data qubits never share a gate)."""
    c, d = base.get_final_qubit_coordinates(), data_qubit_list(base)
    return [(a, b) for i, a in enumerate(d) for b in d[i + 1 :]
            if math.dist(c[a], c[b]) <= CORR_MAX_DIST]


def with_corr(base: stim.Circuit, qf: dict, pair, p: float) -> stim.Circuit:
    """scaled_circuit(base, qf) plus DEPOLARIZE2(p) on `pair` after each round's data-qubit
    depolarization (the DEPOLARIZE1 on exactly the data qubits)."""
    data, out = set(data_qubit_list(base)), stim.Circuit()
    for ins in base:
        one = stim.Circuit()
        one.append(ins)
        out += scaled_circuit(one, qf)
        if ins.name == "DEPOLARIZE1" and {t.value for t in ins.targets_copy()} == data:
            out.append("DEPOLARIZE2", list(pair), [p])
    return out


def matching_for(circuit: stim.Circuit) -> pymatching.Matching:
    return pymatching.Matching.from_detector_error_model(
        circuit.detector_error_model(decompose_errors=True))


def sample(circuit: stim.Circuit, shots: int, seed: int) -> np.ndarray:
    det, _ = circuit.compile_detector_sampler(seed=seed).sample(shots, separate_observables=True)
    return det


@dataclass
class Truth:
    family: str  # "none", "hot_qubit", "hot_coupler", "burst", "tls_switching", "other"
    qubit: int | None = None
    pair: tuple[int, int] | None = None
    factor: float | None = None
    onset_shot: int = 0
    amplitude: float | None = None
    decay_shots: float | None = None
    centre: tuple[float, float] | None = None
    radius: float | None = None
    dwell_shots: float | None = None
    switches: list = field(default_factory=list)  # shots where the TLS state flips
    start_on: bool = False
    background: dict = field(default_factory=dict)


def loguni(rng, lo_hi) -> float:
    return float(np.exp(rng.uniform(*np.log(lo_hi))))


def draw_truth(rng, family: str, base: stim.Circuit, tier: str = "standard") -> Truth:
    rg = TIERS[tier]
    coords = base.get_final_qubit_coordinates()
    qubits = sorted(coords)
    bg = {q: float(np.exp(rng.normal(0.0, BACKGROUND_SIGMA))) for q in qubits}
    if family == "none":
        return Truth("none", background=bg)
    if family in ("hot", "onset"):
        onset = int(rng.integers(N_POST // 5, 4 * N_POST // 5)) if family == "onset" else 0
        return Truth("hot_qubit", qubit=int(rng.choice(qubits)), factor=loguni(rng, rg["hot"]),
                     onset_shot=onset, background=bg)
    if family == "tls":
        dwell = loguni(rng, TLS_DWELL_S) * 1e6 / SHOT_PERIOD_US
        while True:
            on, t_, sw = bool(rng.random() < 0.5), 0.0, []
            first = on
            while True:
                t_ += rng.exponential(dwell)
                if t_ >= N_POST:
                    break
                sw.append(int(t_))
            edges = [0, *sw, N_POST]
            on_time = sum(edges[i + 1] - edges[i] for i in range(len(edges) - 1)
                          if (i % 2 == 0) == first)
            if len(sw) >= TLS_MIN_SWITCHES and TLS_ON_FRAC[0] <= on_time / N_POST <= TLS_ON_FRAC[1]:
                break
        return Truth("tls_switching", qubit=int(rng.choice(qubits)), factor=loguni(rng, rg["tls"]),
                     dwell_shots=dwell, switches=sw, start_on=first, background=bg)
    if family == "corr":
        pairs = corr_pairs(base)
        return Truth(UNLISTED, pair=pairs[int(rng.integers(len(pairs)))],
                     factor=loguni(rng, rg["corr"]), background=bg)
    if family == "coupler":
        pairs = gate_pairs(base)
        return Truth("hot_coupler", pair=pairs[int(rng.integers(len(pairs)))],
                     factor=loguni(rng, rg["coupler"]), background=bg)
    decay = loguni(rng, BURST_DECAY_MS) * 1000.0 / SHOT_PERIOD_US
    return Truth("burst", onset_shot=int(rng.integers(N_POST // 10, 7 * N_POST // 10)),
                 amplitude=loguni(rng, rg["burst"]), decay_shots=decay,
                 centre=(float(rng.uniform(0, 6)), float(rng.uniform(0, 6))),
                 radius=loguni(rng, BURST_RADIUS), background=bg)


def after_circuit(base: stim.Circuit, t: Truth) -> stim.Circuit:
    """The device as it is at the end of the new batch (what the shipped decoder will face)."""
    bg = t.background
    if t.family in ("hot_qubit", "tls_switching"):  # tls: its hot state
        return scaled_circuit(base, {**bg, t.qubit: bg[t.qubit] * t.factor})
    if t.family == "hot_coupler":
        return scaled_circuit(base, bg, {frozenset(t.pair): t.factor})
    if t.family == UNLISTED:
        return with_corr(base, bg, t.pair, t.factor)
    return scaled_circuit(base, bg)  # control, or a burst that has decayed


def burst_batch(base: stim.Circuit, t: Truth, seed: int) -> np.ndarray:
    """Background shots; from the onset every qubit's noise is scaled by
    1 + (A - 1) exp(-(shot - onset) / decay) exp(-r^2 / 2 R^2), r = distance to the centre.
    Shots are grouped into levels of the time profile 3% apart and sampled per level."""
    det = sample(scaled_circuit(base, t.background), N_POST, seed)
    coords = base.get_final_qubit_coordinates()
    spatial = {q: math.exp(-((x - t.centre[0]) ** 2 + (y - t.centre[1]) ** 2) / (2 * t.radius**2))
               for q, (x, y) in coords.items()}
    n_on = int(t.decay_shots * math.log((t.amplitude - 1) / 0.01))
    shots = np.arange(t.onset_shot, min(N_POST, t.onset_shot + n_on))
    g = np.exp(-(shots - t.onset_shot) / t.decay_shots)
    level = np.floor(np.log(g) / math.log(0.97)).astype(int)
    for k, lv in enumerate(np.unique(level)):
        sel = shots[level == lv]
        gl = float(np.mean(g[level == lv]))
        qf = {q: b * (1 + (t.amplitude - 1) * gl * spatial[q]) for q, b in t.background.items()}
        det[sel] = sample(scaled_circuit(base, qf), len(sel), seed + 7 + k)
    return det


def draw_supported(rng, seed: int, index: int, family: str, base: stim.Circuit,
                   tier: str) -> Truth:
    """Standard tier: one draw. Hard tier: draw again until the new batch carries at least
    EVIDENCE_MIN nats (exact expected log-likelihood ratio, eval/evidence.py). The number of
    draws is cached (encrypted, like the tables) so later runs replay them without the tables."""
    if tier == "standard" or family == "none":
        return draw_truth(rng, family, base, tier)
    key = f"qec_drift_d3:evidence:{TIERS[tier]}:{EVIDENCE_MIN}:{seed}:{index}:{family}".encode()
    hit = cache_load(key)
    if hit is not None:
        for _ in range(int(hit["draws"])):
            t = draw_truth(rng, family, base, tier)
        return t
    from evidence import expected_llr
    for n in range(1, 201):
        t = draw_truth(rng, family, base, tier)
        ev = expected_llr(sys.modules[__name__], base, t)
        if ev >= EVIDENCE_MIN:
            cache_save(key, {"draws": np.int64(n), "evidence": np.float64(ev)})
            return t
    raise RuntimeError(f"no supported {family} draw in 200 tries")


def build_instance(seed: int, index: int, family: str,
                   tier: str = "standard") -> tuple[dict, Truth]:
    rng = np.random.default_rng([seed, index, *TIERS[tier].get("salt", [])])
    base = nominal_circuit()
    t = draw_supported(rng, seed, index, family, base, tier)
    s = [int(x) for x in rng.integers(1 << 30, size=3)]
    bg = scaled_circuit(base, t.background)
    pre_det, pre_obs = bg.compile_detector_sampler(seed=s[0]).sample(N_PRE, separate_observables=True)
    if t.family == "burst":
        post = burst_batch(base, t, s[1])
    elif t.family == "tls_switching":
        edges, on = [0, *t.switches, N_POST], t.start_on
        hot = after_circuit(base, t)
        post = np.concatenate([sample(hot if (i % 2 == 0) == on else bg, edges[i + 1] - edges[i],
                                      s[1] + 11 * i) for i in range(len(edges) - 1)])
    elif t.onset_shot:
        post = np.concatenate([sample(bg, t.onset_shot, s[1]),
                               sample(after_circuit(base, t), N_POST - t.onset_shot, s[2])])
    else:
        post = sample(after_circuit(base, t), N_POST, s[1])
    coords = base.get_final_qubit_coordinates()
    qubits = sorted(coords)
    data = {
        "circuit": str(base),
        "p_nominal": P_NOMINAL,
        "distance": DISTANCE,
        "rounds": ROUNDS,
        "shot_period_us": SHOT_PERIOD_US,
        "qubit_coords": {q: tuple(coords[q]) for q in qubits},
        "data_qubits": data_qubit_list(base),
        "measure_qubits": [q for q in qubits if coords[q][0] % 2 == 0],
        "gate_pairs": gate_pairs(base),
        "detector_coords": {k: list(v) for k, v in base.get_detector_coordinates().items()},
        "pre_detectors": pre_det,
        "pre_observables": pre_obs[:, 0].copy(),
        "post_detectors": post,
    }
    if tier != "standard":
        data["tier"] = tier
    return data, t


def anchors(seed: int, index: int, family: str, t: Truth,
            tier: str = "standard") -> tuple[Table, dict]:
    """Exact table of the after-change device and the anchor rates; cached per instance."""
    tag = "" if tier == "standard" else f"{TIERS[tier]}:{EVIDENCE_MIN}:"
    key = f"qec_drift_d3:{tag}{seed}:{index}:{family}".encode()
    hit = cache_load(key)
    if hit is not None:
        info = {k: float(hit[k]) for k in ("stale", "informed", "background", "tail")}
        return Table(hit["idx"], hit["p"]), info
    base = nominal_circuit()
    true_c = after_circuit(base, t)
    tab = Table.from_dem(true_c.detector_error_model())
    if t.family == "tls_switching":
        # The shipped decoder faces the stationary telegraph: half the time hot, half not.
        bg_c = scaled_circuit(base, t.background)
        off = Table.from_dem(bg_c.detector_error_model())
        tab = Table(np.concatenate([tab.idx, off.idx]), np.concatenate([tab.p, off.p]) * 0.5)
        mean_c = scaled_circuit(base, {**t.background,
                                       t.qubit: t.background[t.qubit] * (1 + t.factor) / 2})
        true_c = mean_c  # informed anchor: matching on the time-averaged model
    info = {"stale": tab.ler_of(matching_for(base)), "tail": tab.tail}
    if t.family in ("hot_qubit", "hot_coupler", "tls_switching", UNLISTED):
        info["informed"] = tab.ler_of(matching_for(true_c))
        info["background"] = tab.ler_of(matching_for(scaled_circuit(base, t.background)))
    else:
        info["informed"] = info["background"] = tab.ler_of(matching_for(true_c))
    cache_save(key, {"idx": tab.idx, "p": tab.p, **{k: np.float64(v) for k, v in info.items()}})
    return tab, info


def rule_for(t: Truth, info: dict) -> str:
    """Decided from the true model only: does the change open a decoding gap of GAP_GATE?"""
    if t.family == "none":
        return "control"
    gap = (info["background"] - info["informed"]) / info["background"]
    ok = gap >= GAP_GATE and info["stale"] > info["informed"]
    return "fix" if ok else "diagnosis_only"


def solver_matching(dem_text) -> pymatching.Matching:
    """Validate the returned detector error model; raise ValueError if it is not acceptable."""
    if not isinstance(dem_text, str) or len(dem_text) > MAX_DEM_BYTES:
        raise ValueError("dem must be a string under 5 MB")
    dem = stim.DetectorErrorModel(dem_text)
    if dem.num_detectors != 24 or dem.num_observables != 1:
        raise ValueError("dem must have 24 detectors and 1 observable")
    for inst in dem.flattened():
        if inst.type == "error" and not 0.0 < inst.args_copy()[0] <= 0.5:
            raise ValueError("error probabilities must be in (0, 0.5]")
    return pymatching.Matching.from_detector_error_model(dem)


def harm_factor(e_sol: float, e_stale: float, e_informed: float) -> float:
    """1 if the solver's rate is within HARM_FREE of the worse anchor (shipping the nominal or the
    true model is never harm), falling linearly to 0 at HARM_ZERO worse."""
    x = (e_sol / max(e_stale, e_informed) - 1 - HARM_FREE) / (HARM_ZERO - HARM_FREE)
    return float(np.clip(1 - x, 0.0, 1.0))


def _num(x) -> float | None:
    if isinstance(x, bool) or not isinstance(x, (int, float)) or not math.isfinite(x):
        return None
    return float(x)


def within(est, true: float, tol: float) -> bool:
    est = _num(est)
    return est is not None and est > 0 and abs(math.log(est / true)) <= math.log(tol)


def detail_parts(diag: dict, t: Truth) -> dict[str, tuple[float, float]]:
    """Diagnosis detail by rubric part: {part: (earned, available)}; the earned points sum to
    the detail. Location, size and timing count only under the right kind."""
    tls, hot, cpl = (t.family == f for f in ("tls_switching", "hot_qubit", "hot_coupler"))
    if t.family == "none":
        avail = {"kind": 0.0, "location": 0.0, "size": 0.0, "timing": 0.0}
    elif t.family == UNLISTED:  # its form is not stated, so the kind is all that is graded
        avail = {"kind": 1.0, "location": 0.0, "size": 0.0, "timing": 0.0}
    elif tls:
        avail = {"kind": 0.3, "location": 0.4, "size": 0.15, "timing": 0.15}
    elif hot:
        w_on = 0.25 if t.onset_shot else 0.0  # onset is graded only where it is inside the batch
        avail = {"kind": 0.3, "location": (0.7 - w_on) * 4 / 7, "size": (0.7 - w_on) * 3 / 7,
                 "timing": w_on}
    elif cpl:
        avail = {"kind": 0.3, "location": 0.4, "size": 0.3, "timing": 0.0}
    else:  # burst: onset and decay are its timing; no location or size is graded
        avail = {"kind": 0.3, "location": 0.0, "size": 0.0, "timing": 0.7}
    got = dict.fromkeys(avail, 0.0)
    if diag.get("kind") != t.family:
        return {k: (0.0, v) for k, v in avail.items()}
    got["kind"] = avail["kind"]
    onset = _num(diag.get("onset_shot"))
    if tls or hot:
        q = _num(diag.get("qubit"))
        if q is not None and int(q) == t.qubit:
            got["location"] = avail["location"]
            got["size"] = avail["size"] * within(diag.get("factor"), t.factor, FACTOR_TOL)
        if tls:
            got["timing"] = avail["timing"] * within(diag.get("dwell_shots"), t.dwell_shots,
                                                     DWELL_TOL)
        elif avail["timing"] and onset is not None and abs(onset - t.onset_shot) <= ONSET_TOL_HOT:
            got["timing"] = avail["timing"]
    elif cpl:
        try:
            ok = sorted(int(x) for x in diag.get("pair")) == sorted(t.pair)
        except (TypeError, ValueError):
            ok = False
        if ok:
            got["location"] = avail["location"]
            got["size"] = avail["size"] * within(diag.get("factor"), t.factor, FACTOR_TOL)
    elif t.family == "burst":
        if onset is not None and abs(onset - t.onset_shot) <= ONSET_TOL_BURST:
            got["timing"] += 0.35
        got["timing"] += 0.35 * within(diag.get("decay_shots"), t.decay_shots, FACTOR_TOL)
    return {k: (float(got[k]), float(avail[k])) for k in avail}


def instance_list(seed: int | None, quick: bool,
                  tier: str = "standard") -> tuple[int, list[str]]:
    s = TIERS[tier]["seed"] if seed is None else int(seed)
    if quick:
        return s, list(QUICK_MIX if tier == "standard" else HARD_QUICK_MIX)
    mix = list(FAMILY_MIX if tier == "standard" else HARD_MIX)
    np.random.default_rng([s, 999_999, *TIERS[tier].get("salt", [])]).shuffle(mix)
    return s, mix


def evaluate(solution_path: str, quick: bool = False, seed: int | None = None,
             tier: str = "standard") -> dict:
    s, mix = instance_list(seed, quick, tier)
    nominal_text = str(nominal_circuit().detector_error_model(decompose_errors=True))
    rows = []
    for i, family in enumerate(mix):
        idx = i + 1000 * quick
        data, t = build_instance(s, idx, family, tier)
        ok, out, secs = run_solver(solution_path, data, SOLVE_TIMEOUT_S)
        del data
        tab, info = anchors(s, idx, family, t, tier)
        rule = rule_for(t, info)
        row = {"index": i, "family": family, "truth": asdict(t), "rule": rule, **info,
               "solve_s": round(secs, 1)}
        try:
            if not ok:
                raise ValueError(out)
            diag = out.get("diagnosis") if isinstance(out, dict) else None
            if not isinstance(diag, dict) or not isinstance(diag.get("changed"), bool):
                raise ValueError("diagnosis.changed must be a bool")
            text = out.get("dem")
            if text == nominal_text:
                e_sol = info["stale"]
            else:
                e_sol = tab.ler_of(solver_matching(text))
            changed = diag["changed"]
            harm = harm_factor(e_sol, info["stale"], info["informed"])
            parts = detail_parts(diag, t)
            fix = float(np.clip((info["stale"] - e_sol) / (info["stale"] - info["informed"]),
                                0, 1)) if rule == "fix" else None
            checks = rubric.instance_checks(rule, changed == (rule != "control"), fix, harm, parts)
            row.update(ler_solution=e_sol, harm=harm, fix=fix,
                       detail=float(sum(g for g, _ in parts.values())), changed=changed,
                       score=rubric.total(checks), rubric=checks, reported=diag)
        except Exception as exc:  # any solver failure scores 0 for the instance
            row.update(error=f"{type(exc).__name__}: {exc}"[:300], score=0.0,
                       rubric=rubric.invalid())
        rows.append(row)
    ctrl = [r for r in rows if r["rule"] == "control"]
    fault = [r for r in rows if r["rule"] != "control"]
    return {
        "score": float(np.mean([r["score"] for r in rows])),
        "seed": "public" if seed is None else s,
        "tier": tier,
        "rubric": rubric.VERSION,
        "false_alarm_rate": float(np.mean([r.get("changed", True) for r in ctrl])) if ctrl else None,
        "miss_rate": float(np.mean([not r.get("changed", False) for r in fault])) if fault else None,
        "instances": rows,
    }


