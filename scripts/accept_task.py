"""Run the task acceptance standard (docs/task-standard.md) on each data-out task.

    uv run python scripts/accept_task.py                      # every task in envs/
    uv run python scripts/accept_task.py --task readout_drift
    uv run python scripts/accept_task.py --dry                # score nothing; missing is pending

Gates A1 to A13 and S1 are computed by script. Each run a gate needs goes through the task's
own evaluate.py (agent/envs_grade.py) and is cached under data/envs_hard/reports/<task>/<label>/,
so a second run reads the cache. A5 reuses scripts/envs_legitimacy.py. S1 reads
data/envs_hard/selection.json (scripts/select_tasks.py). Human gates H1 to H3 and justified
flags are read from envs/<task>/REVIEW.json.

Writes data/envs_hard/acceptance.json and docs/envs-acceptance.md. Exits 1 if a gate fails.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
import statistics
import sys
from pathlib import Path

from qec_drift import paths
from qec_drift.agent import envs_grade as eg
from qec_drift.agent.envs_kit import ENVS, TASKS
from qec_drift.scoring import envs_rubric

STANDARD_DOC = paths.REPO_ROOT / "docs" / "task-standard.md"
STANDARD = STANDARD_DOC.read_text()
VERSION = re.search(r"\((standard-v\d+)\)", STANDARD).group(1)
CANARY = re.search(r"`(BENCHMARK DATA SHOULD NEVER[^`]+)`", STANDARD).group(1)
DOC = paths.REPO_ROOT / "docs" / "envs-acceptance.md"
OUT = eg.OUT / "acceptance.json"
BUILD = paths.REPO_ROOT / ".cache" / "accept"
PROBE = paths.REPO_ROOT / "src" / "qec_drift" / "agent" / "envs_probe.py"
M = 0.05
GATES = ("A1", "A2", "A3", "A4", "A5", "A6", "A7", "A8", "A9", "A10", "A11", "A12", "A13")
GATES += ("S1", "H1", "H2", "H3")
REQUIRED = ("TASK.md", "NOTES.md", "evaluate.py", "sandbox/solution.py", "checks/expect.json")
REQUIRED += tuple(f"eval/{f}.py" for f in ("harness", "rubric", "_isolate", "_trivial"))
REQUIRED += ("eval/_reference.py",)
# A number with a physical unit: A13 asks such a TASK.md section for a source or an assumption.
PHYSICAL = re.compile(r"\d\s*(GHz|MHz|kHz|Hz|ns|us|ms|dB|K|mK|deg|percent)\b|\d\s*%")
CITE = re.compile(
    r"arXiv:?\s?\d{4}\.\d{4,5}|doi[:.]|\b(19|20)\d\d\b|assum|stress|design choice", re.I
)

# A4 guess battery: five generic guessers built from trivial and the reference. The base answer
# is cached per instance (keyed by a hash of the data), so the reference guessers cost one
# reference run per seed. Generated into .cache/accept/, which is not committed.
BATTERY = {
    "accept_triv_changed": ("trivial", "changed"),
    "accept_triv_coin": ("trivial", "coin"),
    "accept_ref_changed": ("reference", "changed"),
    "accept_ref_unchanged": ("reference", "unchanged"),
    "accept_ref_coin": ("reference", "coin"),
}
WRAPPER = '''"""Generated by scripts/accept_task.py (gate A4): {base}, change call forced to {mode}.
"""
import hashlib, importlib.util, os, pickle, sys
BASE, CACHE, MODE = {path!r}, {cache!r}, {mode!r}
sys.path.insert(0, os.path.dirname(BASE))


def solve(data):
    key = hashlib.sha256(pickle.dumps(data, protocol=4)).hexdigest()
    hit = os.path.join(CACHE, key + ".pkl")
    if os.path.exists(hit):
        with open(hit, "rb") as f:
            out = pickle.load(f)
    else:
        spec = importlib.util.spec_from_file_location("_base", BASE)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        out = mod.solve(data)
        os.makedirs(CACHE, exist_ok=True)
        with open(hit + ".%d" % os.getpid(), "wb") as f:
            pickle.dump(out, f)
        os.replace(hit + ".%d" % os.getpid(), hit)
    out["diagnosis"]["changed"] = {{"changed": True, "unchanged": False}}.get(
        MODE, int(key[:8], 16) % 2 == 1)
    return out
'''


def _script(name: str):
    spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(f"{name}.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def gate(status: str, detail: str, **evidence) -> dict:
    return dict(status=status, detail=detail, **({"evidence": evidence} if evidence else {}))


def verdict(gates: dict) -> str:
    st = {g["status"] for g in gates.values()}
    return "rejected" if "fail" in st else "accepted" if st == {"pass"} else "open"


def uncited_sections(text: str) -> list[str]:
    """TASK.md sections that state a physical quantity but cite nothing and call it nothing."""
    sections = re.findall(r"^## (.+)\n((?:(?!^## ).*\n?)*)", text, re.M)
    return [h for h, body in sections if PHYSICAL.search(body) and not CITE.search(body)]


class Task:
    def __init__(self, task: str, dry: bool):
        self.task, self.dry, self.dir = task, dry, ENVS / task
        self.paper = [eg.seed_tag(s) for s in eg.CONFIG["paper_seeds"]]
        self.check = ["public", *self.paper[: eg.CONFIG["check_seeds"]]]
        self.ceilings = {
            p.stem: p for p in sorted((self.dir / "ceilings").glob("*.py"))
            if not p.name.startswith("_")
        }  # fmt: skip

    # stored and new runs -------------------------------------------------------------------
    def _dest(self, label: str, tag: str) -> Path:
        return eg.OUT / "reports" / self.task / label / f"{tag}.json"

    def reports(self, label: str, sol: Path, tags: list[str], ablate=False) -> dict | None:
        """{tag: report}, scoring what is missing unless --dry; None if any is missing."""
        missing = [t for t in tags if not self._dest(label, t).exists()]
        if missing and self.dry:
            return None
        if missing:
            which = [None if t == "public" else int(t) for t in tags]
            return eg.reports(self.task, sol, label, which, ablate)
        return {t: json.loads(self._dest(label, t).read_text()) for t in tags}

    def scores(self, label: str, sol: Path, tags: list[str], ablate=False) -> list[float] | None:
        reps = self.reports(label, sol, tags, ablate)
        return None if reps is None else [reps[t]["score"] for t in tags]

    def base(self, name: str) -> Path:
        return self.dir / eg.BASELINES[name]

    # gates ---------------------------------------------------------------------------------
    def a1(self) -> dict:
        missing = [f for f in REQUIRED if not (self.dir / f).exists()]
        iso = {hashlib.sha256(p.read_bytes()).hexdigest() for p in ENVS.glob("*/eval/_isolate.py")}
        rubric = self.dir / "eval" / "rubric.py"
        found = (
            re.search(r'^VERSION = "([^"]+)"', rubric.read_text(), re.M) if not missing else None
        )
        if not missing and len(iso) == 1 and found:
            return gate("pass", f"rubric {found.group(1)}")
        return gate("fail", f"missing {missing}; {len(iso)} versions of _isolate.py; rubric "
                    f"version {'found' if found else 'missing'}")  # fmt: skip

    def a2(self, fresh: bool) -> dict:
        got = {}
        for name in ("trivial", "reference"):
            label = f"accept_rerun_{name}"
            if fresh and not self.dry:
                self._dest(label, "public").unlink(missing_ok=True)
            pair = (self.reports(name, self.base(name), ["public"]),
                    self.reports(label, self.base(name), ["public"]))  # fmt: skip
            if None in pair:
                return gate("pending", "re-runs not scored yet")
            got[name] = [p["public"] for p in pair]
        # order-free: a seed's instance order may change between versions, its scores may not
        t0, t1 = (sorted(i["score"] for i in rep["instances"]) for rep in got["trivial"])
        r0, r1 = (rep["score"] for rep in got["reference"])
        ok = t0 == t1 and abs(r0 - r1) <= 0.01
        return gate("pass" if ok else "fail",
                    f"trivial {'identical' if t0 == t1 else 'DIFFERS'} per instance; reference "
                    f"{r0:.4f} stored vs {r1:.4f} re-run", reference=[r0, r1])  # fmt: skip

    def a3(self) -> dict:
        s = self.scores("trivial", self.base("trivial"), self.paper)
        if s is None:
            return gate("pending", "trivial not scored on every paper seed")
        m = statistics.mean(s)
        return gate("pass" if abs(m - 0.5) <= 0.02 else "fail", f"trivial {m:.3f}", trivial=m)

    def a4(self) -> dict:
        triv = self.scores("trivial", self.base("trivial"), self.check)
        over, pend = {}, []
        for name, (base, mode) in BATTERY.items():
            f = BUILD / self.task / f"{name}.py"
            f.parent.mkdir(parents=True, exist_ok=True)
            cache = BUILD / "answers" / self.task / base
            f.write_text(WRAPPER.format(base=base, mode=mode, path=str(self.base(base).resolve()),
                                        cache=str(cache)))  # fmt: skip
            s = self.scores(name, f, self.check)
            if s is None or triv is None:
                pend.append(name)
                continue
            d = [a - b for a, b in zip(s, triv, strict=True)]
            # a coin's score on one seed has binomial spread near 0.09: judge its mean
            over[name] = statistics.mean(d) if mode == "coin" else max(d)
        if pend:
            return gate("pending", f"guess battery not scored: {', '.join(pend)}")
        bad = {n: d for n, d in over.items() if d > M}
        worst = max(over, key=over.get)
        detail = f"worst {worst} {over[worst]:+.3f} vs trivial on {len(self.check)} check seeds"
        if bad:
            detail += "; OVER: " + ", ".join(f"{n} {d:+.3f}" for n, d in bad.items())
        return gate("fail" if bad else "pass", detail, over_trivial=over)

    def a5(self, legitimacy) -> dict:
        if self.dry:
            return gate("pending", "--dry: run scripts/envs_legitimacy.py")
        rows = [r for r in legitimacy.task_rows(self.task) if r["kind"] in ("lazy", "leak")]
        bad = [r["check"] for r in rows if not r["ok"]]
        worst = max(rows, key=lambda r: r["score"] - r["bar"])
        detail = (f"{len(rows)} lazy and leak checks; closest {worst['check']} "
                  f"{worst['score']:.3f} against bar {worst['bar']:.3f}")  # fmt: skip
        return gate("fail" if bad else "pass", detail + (f"; OVER: {bad}" if bad else ""))

    def a6(self) -> dict:
        reps = self.reports("accept_probe", PROBE, ["public"])
        if reps is None:
            return gate("pending", "probe not run")
        errs = {i.get("error", "") for i in reps["public"]["instances"]}
        found = sorted({c for e in errs for c in re.findall(r"PROBE open=([\w,]+)", e)})
        if not found:
            return gate("fail", f"probe did not report: {sorted(errs)[:2]}")
        chans = sorted({c for f in found for c in f.split(",") if c != "none"})
        if chans:
            return gate("pending", "local mode, open: " + ", ".join(chans) + " (closed only by "
                        "a sealed harness)", open=chans)  # fmt: skip
        return gate("pass", "every channel closed")

    def a7(self) -> dict:
        ref = self.base("reference")
        s = self.scores("reference_swapped_data", ref, self.paper, ablate=True)
        t = self.scores("trivial", self.base("trivial"), self.paper)
        if s is None or t is None:
            return gate("pending", "ablation not scored on every paper seed")
        a, b = statistics.mean(s), statistics.mean(t)
        ok = a <= b + M
        return gate("pass" if ok else "fail", f"reference on swapped data {a:.3f}, trivial {b:.3f}")

    def known(self) -> dict[str, Path]:
        return {"reference": self.base("reference"), **self.ceilings}

    def a8(self) -> dict:
        means = {n: statistics.mean(s) for n, p in self.known().items()
                 if (s := self.scores(n, p, self.paper)) is not None}  # fmt: skip
        if "reference" not in means:
            return gate("pending", "reference not scored on every paper seed")
        best = max(means, key=means.get)
        ok = means[best] >= 0.85
        return gate("pass" if ok else "fail", f"best known {best} {means[best]:.3f}", known=means)

    def a9(self) -> dict:
        r = self.scores("reference", self.base("reference"), self.paper)
        t = self.scores("trivial", self.base("trivial"), self.paper)
        if r is None or t is None:
            return gate("pending", "reference or trivial missing")
        a, b = statistics.mean(r), statistics.mean(t)
        return gate("pass" if a >= b + 0.10 else "fail", f"reference {a:.3f}, trivial {b:.3f}")

    def a10(self) -> dict:
        best: dict[str, tuple[float, int, str]] = {}
        few: dict[str, int] = {}
        for name, p in self.known().items():
            reps = self.reports(name, p, self.paper)
            if reps is None:
                continue
            for check, (v, n) in envs_rubric.check_stats(self.task, reps.values()).items():
                if check == "valid_answer" or not n:
                    continue
                if n < 10:
                    few[check] = max(few.get(check, 0), n)
                    continue
                best[check] = max(best.get(check, (v, n, name)), (v, n, name))
        if not best:
            return gate("pending", "no reference reports on the paper seeds")
        few = {c: n for c, n in few.items() if c not in best}
        low = sorted(c for c, v in best.items() if v[0] < 0.70)
        detail = "best known per check: " + ", ".join(
            f"{c} {v[0]:.2f} ({v[2]}, n={v[1]})" for c, v in sorted(best.items())
        )
        if low:
            detail = f"below 0.70: {', '.join(low)}; " + detail
        if few:
            detail += "; too few instances to judge: " + ", ".join(sorted(few))
        return gate("flag" if low else "pass", detail, low=low, too_few=sorted(few))

    def a11(self) -> dict:
        s = self.scores("reference", self.base("reference"), self.paper)
        if s is None:
            return gate("pending", "reference not scored on every paper seed")
        se = statistics.stdev(s) / len(s) ** 0.5
        ok = se <= 0.03
        return gate("pass" if ok else "fail", f"reference standard error {se:.3f}, {len(s)} seeds")

    def a12(self) -> dict:
        reps = self.reports("reference", self.base("reference"), self.paper)
        if reps is None:
            return gate("pending", "no reference runs")
        t = statistics.mean(
            sum(i.get("solve_s", i.get("runtime_s", 0.0)) for i in rep["instances"])
            for rep in reps.values()
        )
        return gate("pass" if t < 600 else "fail", f"reference solve time {t:.0f} s per "
                    "evaluation (sum over instances, one core)", solve_s=t)  # fmt: skip

    def a13(self) -> dict:
        text = (self.dir / "TASK.md").read_text()
        bare, has = uncited_sections(text), CANARY in text
        status = "fail" if not has else "flag" if bare else "pass"
        detail = "canary present" if has else "canary MISSING"
        if bare:
            detail += f"; sections with numbers but no source or assumption: {bare}"
        return gate(status, detail, uncited=bare)

    def s1(self) -> dict:
        f = eg.OUT / "selection.json"
        rows = json.loads(f.read_text())["tasks"] if f.exists() else []
        mine = [t for t in rows if t["task"] == self.task]
        if not mine:
            return gate("pending", "run scripts/select_tasks.py first")
        t = mine[0]
        st = {"included": "pass", "excluded": "fail"}.get(t["status"], "pending")
        if t.get("best") is None:
            return gate(st if st == "fail" else "pending", "no agent runs yet")
        ci = t.get("best_interval")
        span = f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else ""
        return gate(st, f"best agent {t['best']} passes {t['best_pass']:.2f}{span}")

    def human(self) -> tuple[dict, dict]:
        f = self.dir / "REVIEW.json"
        rec = json.loads(f.read_text()) if f.exists() else {}
        signed = [r for r in rec.get("h1", []) if r.get("signed") and not r.get("advisory")]
        h1 = gate("pass" if len(signed) >= 2 else "pending", f"{len(signed)} of 2 sign-offs")
        ratio = [r["score_ratio"] for r in rec.get("h2", []) if "score_ratio" in r]
        h2 = gate(("pass" if max(ratio) >= 0.9 else "fail") if ratio else "pending",
                  f"blind re-implementation at {max(ratio):.0%} of reference" if ratio
                  else "no blind re-implementation yet")  # fmt: skip
        h3 = rec.get("h3", [])
        h3 = gate(("pass" if all(r.get("explained") for r in h3) else "fail") if h3 else "pending",
                  f"{len(h3)} outlier reviews" if h3 else "no outlier review yet")  # fmt: skip
        return {"H1": h1, "H2": h2, "H3": h3}, rec.get("flags", {})

    def run(self, fresh: bool, legitimacy) -> dict:
        g = {
            "A1": self.a1(), "A2": self.a2(fresh), "A3": self.a3(), "A4": self.a4(),
            "A5": self.a5(legitimacy), "A6": self.a6(), "A7": self.a7(), "A8": self.a8(),
            "A9": self.a9(), "A10": self.a10(), "A11": self.a11(), "A12": self.a12(),
            "A13": self.a13(), "S1": self.s1(),
        }  # fmt: skip
        human, flags = self.human()
        g.update(human)
        for k, v in g.items():
            if v["status"] == "flag" and flags.get(k):
                v["status"], v["justified"] = "pass", flags[k]
        return dict(task=self.task, standard=VERSION, verdict=verdict(g), gates=g)


def markdown(cards: list[dict]) -> str:
    lines = [
        f"# Data-out tasks: acceptance cards ({VERSION})",
        "",
        "Generated by scripts/accept_task.py; do not edit. Gates and pass rules: "
        "[task-standard.md](task-standard.md). Hard tier, paper seeds.",
        "",
        "| task | verdict | " + " | ".join(GATES) + " |",
        "|---|---|" + "---|" * len(GATES),
    ]
    for c in cards:
        cells = " | ".join(c["gates"][k]["status"] for k in GATES)
        lines.append(f"| {c['task']} | {c['verdict']} | {cells} |")
    for c in cards:
        lines += ["", f"## {c['task']}: {c['verdict']}", ""]
        for k in GATES:
            g = c["gates"][k]
            why = f" Justified: {g['justified']}" if "justified" in g else ""
            lines.append(f"- **{k}** {g['status']}: {g['detail']}{why}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--task", choices=sorted(TASKS))
    ap.add_argument("--dry", action="store_true", help="score nothing; missing runs are pending")
    ap.add_argument("--fresh", action="store_true", help="redo the A2 re-runs")
    a = ap.parse_args(argv)
    legitimacy = _script("envs_legitimacy")
    cards = []
    for task in [a.task] if a.task else sorted(TASKS):
        cards.append(Task(task, a.dry).run(a.fresh, legitimacy))
        print(f"{task}: {cards[-1]['verdict']}", flush=True)
    old = json.loads(OUT.read_text())["tasks"] if OUT.exists() else []
    cards = sorted([c for c in old if c["task"] not in {d["task"] for d in cards}] + cards,
                   key=lambda c: c["task"])  # fmt: skip
    OUT.write_text(json.dumps(dict(standard=VERSION, tasks=cards), indent=1) + "\n")
    DOC.write_text(markdown(cards))
    print(DOC.read_text())
    return 1 if any(c["verdict"] == "rejected" for c in cards) else 0


if __name__ == "__main__":
    sys.exit(main())
